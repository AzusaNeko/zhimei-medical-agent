#: 只有工单被人工【实际接单】后，才允许发送下面这句（对应 accepted_at 非空）
HANDOFF_ACCEPTED_NOTICE = "客服已接入，正在为您处理。"

TAKEOVER_ACTIVE_NOTICE = "当前会话已由人工客服接管。"


# ══════════════════════════════════════════════════════════════
#  用户主动要求转人工：安抚话术（固定模板，不走 LLM）
# ══════════════════════════════════════════════════════════════
#
# ★ 为什么也是固定模板：这几句是**关于流程的承诺**（"再说几次就转"），
#   让模型现场措辞，它可能随口承诺一个我们并不执行的时限或次数 ——
#   那比态度生硬严重得多。
#
# ★ 为什么需要"连续三次"这道门槛：中文里"人工"两个字出现得太随意
#   （"人工客服是不是 24 小时"、"你们人工费怎么算"），一次性全转出去，
#   转人工率会虚高、坐席被无谓占用 —— 这与项目里"二次复核白升"那个问题同源。
#   但门槛必须**如实告诉用户**，否则就是吊着他。

#: 用户要求转人工时，还没到阈值时的安抚话术。{n} = 第几次，{total} = 阈值。
#:
#: ★ 措辞里把"连续 N 次"这条规则明说出来，是刻意的：
#:   含糊其辞（"稍后为您转接"）会让人以为下一次就转，而我们并不打算转 ——
#:   那是在骗用户。把机制讲清楚，他可以选择继续说明，也可以照着做。
HUMAN_REQUEST_REASSURE = (
    "我在的，您别急。转人工是可以的 —— 为了不把您误转出去"
    "（有时顾客只是顺口提到「人工」两个字），需要您**明确再确认**："
    "连续说 {total} 次「转人工」，我就直接为您转接人工客服。"
    "这是第 {n} 次。\n"
    "这期间我先帮您把已经说过的情况整理成摘要，同事接手时能直接看到，"
    "您不用再讲一遍。您也可以继续跟我说具体是哪里不满意，我这边能答的先答。"
)

#: 已达到阈值：确认转接（这一刻真的建单并停用 AI）
HUMAN_REQUEST_GRANTED = (
    "好的，已按您的要求为您转接人工客服。\n"
    "AI 的自动回复已经停止，人工客服会尽快接手；"
    "在同事接手之前，您继续说的情况都会被记录下来，不会丢。"
)

#: 已经在接管状态（AI 已停），用户又要求转人工时的安抚话术。
HUMAN_REQUEST_ALREADY = (
    "已经有一位人工客服在处理您的问题了，您别急。"
    "（这是您第 {n} 次提到转人工，已记录。）\n"
    "您刚才补充的内容同事都能看到；如果您觉得等得太久，"
    "把最要紧的那句话再说一遍，我把它标成加急。"
)


def notice_for(tier: str | None) -> str:
    return {"P0": P0_NOTICE, "P1": P1_NOTICE}.get(tier or "", P1_NOTICE)
