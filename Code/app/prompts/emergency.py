"""
紧急提示：固定模板，【不走 LLM】。

为什么不让模型现场措辞：
紧急提示必须零延迟、零幻觉、零歧义，而且应当是【预先通过合规审查的固定话术】。
把最不能出错的场景交给最不稳定的环节，是设计错误。
"""

